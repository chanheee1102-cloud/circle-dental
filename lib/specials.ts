  /** STRENGTHS 의 key 와 일치. 아이콘을 공유한다. */
  key: string;
  /** 원문 eyebrow. */
  eyebrow: string;
  /** 화면용 제목. */
  title: string;
  /** ★ 원문 그대로. */
  body: string;
  /** 잘라낸 사진(왼쪽 색면·번호 제거본). */
